package dev.swirlit.indezy.pdf;

import dev.swirlit.indezy.model.enums.DocumentLanguage;
import dev.swirlit.indezy.model.enums.SkillLevel;

/** French and English text of the dossier de compétences PDF. */
enum DossierLabel {
    TITLE("Dossier de compétences", "Skills profile"),
    SUMMARY("Profil", "Summary"),
    SKILLS("Compétences", "Skills"),
    YEARS("%d an(s)", "%d year(s)"),
    LANGUAGES("Langues", "Languages"),
    CERTIFICATIONS("Certifications", "Certifications"),
    MISSIONS("Expériences", "Experience"),
    NO_MISSIONS("Aucune mission signée enregistrée.", "No signed mission recorded."),
    SINCE("depuis %s", "since %s"),
    CLIENT_HIDDEN("Client communiqué sur demande", "Client disclosed on request"),
    STACK("Environnement : %s", "Environment: %s"),
    FOOTER("Généré par Indezy le %s", "Generated by Indezy on %s");

    private final String french;
    private final String english;

    DossierLabel(String french, String english) {
        this.french = french;
        this.english = english;
    }

    String in(DocumentLanguage language) {
        return language == DocumentLanguage.EN ? english : french;
    }

    String format(DocumentLanguage language, Object... values) {
        return String.format(language.locale(), in(language), values);
    }

    static String level(SkillLevel level, DocumentLanguage language) {
        boolean english = language == DocumentLanguage.EN;
        return switch (level) {
            case BEGINNER -> english ? "beginner" : "débutant";
            case INTERMEDIATE -> english ? "intermediate" : "intermédiaire";
            case ADVANCED -> english ? "advanced" : "confirmé";
            case EXPERT -> "expert";
        };
    }
}
