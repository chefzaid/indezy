package dev.swirlit.indezy.pdf;

import dev.swirlit.indezy.model.enums.DocumentLanguage;
import dev.swirlit.indezy.model.enums.LostReason;

/** French and English text of the yearly review PDF. */
enum YearlyReviewLabel {
    TITLE("Bilan %d", "%d in review"),
    REVENUE("Chiffre d'affaires", "Revenue"),
    DAYS("Jours travaillés", "Days worked"),
    AVERAGE_RATE("TJM moyen", "Average daily rate"),
    MISSIONS("Missions", "Missions"),
    VERSUS("%s par rapport à %d", "%s on %d"),
    NO_COMPARISON("Pas de chiffre en %d", "Nothing in %d"),
    MISSIONS_TITLE("Missions de l'année", "Missions of the year"),
    NO_MISSIONS("Aucune mission signée sur l'année.", "No mission signed in the year."),
    COLUMN_MISSION("Mission", "Mission"),
    COLUMN_PERIOD("Période", "Period"),
    COLUMN_DAYS("Jours", "Days"),
    COLUMN_RATE("TJM", "Rate"),
    COLUMN_REVENUE("Montant", "Amount"),
    ONGOING("en cours", "ongoing"),
    ESTIMATED("* jours estimés d'après les jours par an de la mission, faute de compte rendu d'activité",
        "* days estimated from the mission's days per year, as no activity report says"),
    PIPELINE_TITLE("Opportunités", "Opportunities"),
    PIPELINE("%d ouvertes · %d gagnées · %d refusées", "%d opened · %d won · %d declined"),
    CONVERSION("%d %% de gagnées parmi celles décidées", "%d%% of the decided ones won"),
    LOST_REASONS("Raisons des refus : %s", "Why they were declined: %s"),
    SKILLS_TITLE("Compétences les plus demandées", "Skills most asked for"),
    NO_SKILLS("Aucune compétence citée par les opportunités de l'année.", "No skill named by the year's opportunities."),
    SKILL("%s : %d opportunité(s)", "%s: %d opportunit(ies)"),
    NETWORK_TITLE("Réseau", "Network"),
    NETWORK("%d nouveaux clients · %d nouvelles ESN · %d nouveaux contacts · %d échanges",
        "%d new clients · %d new agencies · %d new contacts · %d exchanges"),
    FOOTER("Généré par Indezy le %s", "Generated by Indezy on %s");

    private final String french;
    private final String english;

    YearlyReviewLabel(String french, String english) {
        this.french = french;
        this.english = english;
    }

    String in(DocumentLanguage language) {
        return language == DocumentLanguage.EN ? english : french;
    }

    String format(DocumentLanguage language, Object... values) {
        return String.format(ActivityReportLabel.locale(language), in(language), values);
    }

    static String reason(LostReason reason, DocumentLanguage language) {
        boolean english = language == DocumentLanguage.EN;
        return switch (reason) {
            case RATE_TOO_LOW -> english ? "Rate too low" : "TJM trop bas";
            case POSITION_FILLED -> english ? "Position filled" : "Poste pourvu";
            case NO_RESPONSE -> english ? "No response" : "Pas de réponse";
            case PROFILE_MISMATCH -> english ? "Profile mismatch" : "Profil inadapté";
            case CLIENT_CANCELED -> english ? "Canceled by the client" : "Annulé par le client";
            case ACCEPTED_OTHER_OFFER -> english ? "Accepted another offer" : "Autre offre acceptée";
            case OTHER -> english ? "Other" : "Autre";
        };
    }
}
