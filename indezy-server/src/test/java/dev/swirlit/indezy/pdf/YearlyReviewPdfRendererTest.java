package dev.swirlit.indezy.pdf;

import dev.swirlit.indezy.dto.YearlyReviewDto;
import dev.swirlit.indezy.dto.YearlyReviewDto.Mission;
import dev.swirlit.indezy.model.enums.DocumentLanguage;
import dev.swirlit.indezy.model.enums.LostReason;
import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.text.PDFTextStripper;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.time.LocalDate;
import java.util.Arrays;
import java.util.List;
import java.util.stream.IntStream;

import static org.assertj.core.api.Assertions.assertThat;

class YearlyReviewPdfRendererTest {

    private static final LocalDate TODAY = LocalDate.of(2026, 10, 27);
    private static final List<YearlyReviewDto.ReasonCount> EVERY_REASON = Arrays.stream(LostReason.values())
        .map(reason -> new YearlyReviewDto.ReasonCount(reason, 1)).toList();

    private final YearlyReviewPdfRenderer renderer = new YearlyReviewPdfRenderer();

    @Test
    void writesTheYearInFrenchWithItsComparisonEstimatesAndEveryLostReason() throws IOException {
        YearlyReviewDto review = new YearlyReviewDto(2026, "Alice Martin",
            List.of(new Mission(1L, "Lead Java", "Acme", 600, LocalDate.of(2026, 1, 5), LocalDate.of(2026, 6, 30), 110, true, 66_000L),
                new Mission(2L, "Dev Kafka", null, null, LocalDate.of(2026, 9, 1), null, 40.5, false, null)),
            new YearlyReviewDto.Totals(66_000, 150.5, 600, 2), new YearlyReviewDto.Totals(55_000, 100, 550, 1),
            new YearlyReviewDto.Pipeline(12, 2, 7, 22, EVERY_REASON),
            List.of(new YearlyReviewDto.SkillCount("Java", 5)), new YearlyReviewDto.Network(3, 2, 7, 15));

        String text = text(renderer.render(review, DocumentLanguage.FR, TODAY));

        assertThat(text).contains("Bilan 2026", "Alice Martin", "+20 % par rapport à 2025", "Lead Java · Acme", "en cours", "40,5*",
            "* jours estimés", "12 ouvertes · 2 gagnées · 7 perdues", "22 % de gagnées parmi celles décidées", "TJM trop bas (1)",
            "Poste pourvu", "Pas de réponse", "Profil inadapté", "Annulé par le client", "Autre offre acceptée", "Autre (1)",
            "Java : 5 opportunité(s)", "3 nouveaux clients · 2 nouvelles ESN · 7 nouveaux contacts · 15 échanges",
            "Généré par Indezy le 27 oct. 2026");
    }

    @Test
    void writesAnEmptyYearInEnglishWithEveryLostReason() throws IOException {
        YearlyReviewDto review = new YearlyReviewDto(2025, "Bob", List.of(), new YearlyReviewDto.Totals(0, 0, null, 0),
            new YearlyReviewDto.Totals(0, 0, null, 0), new YearlyReviewDto.Pipeline(7, 0, 7, 0, EVERY_REASON), List.of(),
            new YearlyReviewDto.Network(0, 0, 0, 0));

        String text = text(renderer.render(review, DocumentLanguage.EN, TODAY));

        assertThat(text).contains("2025 in review", "Nothing in 2024", "No mission signed in the year.", "Rate too low",
            "Position filled", "No response", "Profile mismatch", "Canceled by the client", "Accepted another offer", "Other (1)",
            "No skill named by the year's opportunities.", "Generated by Indezy on 27 Oct 2026")
            .doesNotContain("days estimated");
    }

    @Test
    void continuesALongYearOnAnotherPage() throws IOException {
        List<Mission> missions = IntStream.range(0, 60).mapToObj(index -> new Mission((long) index, "Mission " + index, "Client",
            500, LocalDate.of(2026, 1, 1), LocalDate.of(2026, 1, 31), 3, true, 1_500L)).toList();
        YearlyReviewDto review = new YearlyReviewDto(2026, "Alice", missions, new YearlyReviewDto.Totals(90_000, 180, 500, 60),
            new YearlyReviewDto.Totals(0, 0, null, 0), new YearlyReviewDto.Pipeline(0, 0, 0, null, List.of()), List.of(),
            new YearlyReviewDto.Network(0, 0, 0, 0));

        try (PDDocument pdf = Loader.loadPDF(renderer.render(review, DocumentLanguage.EN, TODAY))) {
            assertThat(pdf.getNumberOfPages()).isGreaterThan(1);
            assertThat(pdf.getDocumentInformation().getTitle()).isEqualTo("2026 in review");
            assertThat(new PDFTextStripper().getText(pdf)).contains("Mission 59");
        }
    }

    private static String text(byte[] bytes) throws IOException {
        try (PDDocument pdf = Loader.loadPDF(bytes)) {
            return new PDFTextStripper().getText(pdf).replaceAll("[ \\t\\u00a0\\u202f]+", " ");
        }
    }
}
