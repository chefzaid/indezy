// Lists every source file of src/app in src/app/coverage-sources.ts, which coverage-sources.spec.ts imports, so the
// coverage report counts the files no spec imports at 0% instead of leaving them out. `--check` fails when the list is
// out of date (`npm run lint` runs it); without it, the list is written again (`npm run coverage-sources`).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = fileURLToPath(new URL('../src/app/', import.meta.url));
const target = join(app, 'coverage-sources.ts');

function sources(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      return sources(path);
    }
    return entry.name.endsWith('.ts') && !entry.name.endsWith('.spec.ts') && path !== target ? [path] : [];
  });
}

const list = sources(app).map(path => relative(app, path).replaceAll('\\', '/').replace(/\.ts$/, '')).sort();
const content = `// Generated by scripts/coverage-sources.mjs (npm run coverage-sources): every source file, for coverage-sources.spec.ts.
export const COVERAGE_SOURCES: readonly string[] = [
${list.map(source => `  '${source}',`).join('\n')}
];
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // A missing list is out of date too.
  }
  if (current !== content) {
    console.error('src/app/coverage-sources.ts is out of date: run `npm run coverage-sources`.');
    process.exit(1);
  }
} else {
  writeFileSync(target, content);
  console.log(`Listed ${list.length} source files in src/app/coverage-sources.ts`);
}
