import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { NetworkService } from './network.service';

describe('NetworkService', () => {
  it('reads, joins and leaves the network, checks handles and reads members\' cards', () => {
    TestBed.configureTestingModule({ providers: [provideHttpClient(), provideHttpClientTesting()] });
    const service = TestBed.inject(NetworkService);
    const http = TestBed.inject(HttpTestingController);
    const fields = { photo: true, headline: true, stack: true, location: false, availability: true, languages: true, remote: true };
    service.membership().subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/membership'));
    const availability = { mode: 'LISTENING' as const, date: null };
    service.join('camille', fields, availability).subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/membership')).request.body)
      .toEqual({ handle: 'camille', fields, availability });
    service.verify().subscribe();
    http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/membership/verification'));
    service.leave().subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/membership'));
    service.handle('cam ille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/handles/cam%20ille'));
    service.directory({ skill: ' Kafka ', city: '', availability: 'LISTENING', remote: true, page: 2 }).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/members')).request.params.toString())
      .toBe('page=2&skill=Kafka&availability=LISTENING&remote=true');
    service.directory({}).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/members')).request.params.toString()).toBe('page=0');
    service.post('Bonjour').subscribe();
    expect(http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/posts')).request.body).toEqual({ text: 'Bonjour' });
    service.like(5, true).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/posts/5/like'));
    service.like(5, false).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/posts/5/like'));
    service.likers(5).subscribe();
    http.expectOne(call => call.url.endsWith('/network/posts/5/likes'));
    service.deletePost(5).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/posts/5'));
    service.feed().subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/feed')).request.params.get('page')).toBe('0');
    service.memberPosts('leo', 2).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/members/leo/posts')).request.params.get('page')).toBe('2');
    service.member('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille'));
    service.page('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille/page'));
    service.follow('camille').subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/members/camille/follow'));
    service.unfollow('camille').subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/members/camille/follow'));
    service.followers('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille/followers'));
    service.following('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille/following'));
    service.mute('leo', true).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/members/leo/mute'));
    service.mute('leo', false).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/members/leo/mute'));
    service.block('leo', true).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/members/leo/block'));
    service.block('leo', false).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/members/leo/block'));
    service.restrictions().subscribe();
    http.expectOne(call => call.url.endsWith('/network/restrictions'));
    service.removeFollower('leo').subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/followers/leo'));
    http.verify();
  });
});
