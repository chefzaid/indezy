import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { NetworkService } from './network.service';
import { SILENT_HTTP_ERRORS } from '../../interceptors/error.interceptor';

describe('NetworkService', () => {
  it('asks how many posts are newer, the trending tags and the tags starting with what was typed', () => {
    TestBed.configureTestingModule({ providers: [provideHttpClient(), provideHttpClientTesting()] });
    const service = TestBed.inject(NetworkService);
    const http = TestBed.inject(HttpTestingController);
    let count = -1;
    service.newerCount('2026-11-16T10:00:00').subscribe(found => count = found);
    const newer = http.expectOne(call => call.url.endsWith('/network/feed/newer'));
    expect(newer.request.params.get('since')).toBe('2026-11-16T10:00:00');
    newer.flush({ count: 3 });
    expect(count).toBe(3);
    service.trendingTags().subscribe();
    http.expectOne(call => call.url.endsWith('/network/tags/trending'));
    service.mentions('ca').subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/mentions')).request.params.get('q')).toBe('ca');
    service.suggestTags('ka').subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/tags/suggest')).request.params.get('q')).toBe('ka');
    service.trendingTags(true).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/tags/trending')).request.context.get(SILENT_HTTP_ERRORS)).toBeTrue();
    service.suggestions(true).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/suggestions')).request.context.get(SILENT_HTTP_ERRORS)).toBeTrue();
    service.searchMembers('bob mar', 1).subscribe();
    const members = http.expectOne(call => call.url.endsWith('/network/search/members'));
    expect(members.request.params.get('q')).toBe('bob mar');
    expect(members.request.params.get('page')).toBe('1');
    service.searchPosts('kafka').subscribe();
    const posts = http.expectOne(call => call.url.endsWith('/network/search/posts'));
    expect(posts.request.params.get('q')).toBe('kafka');
    expect(posts.request.params.get('page')).toBe('0');
    http.verify();
  });

  it('reads, joins and leaves the network, checks handles and reads members\' cards', () => {
    TestBed.configureTestingModule({ providers: [provideHttpClient(), provideHttpClientTesting()] });
    const service = TestBed.inject(NetworkService);
    const http = TestBed.inject(HttpTestingController);
    const fields = { photo: true, headline: true, stack: true, location: false, availability: true, languages: true, remote: true };
    service.membership().subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/membership'));
    const availability = { mode: 'LISTENING' as const, date: null };
    service.join('camille', fields, availability).subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/membership')).request.body)
      .toEqual({ handle: 'camille', fields, availability });
    service.verify().subscribe();
    http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/membership/verification'));
    service.leave().subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/membership'));
    service.handle('cam ille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/handles/cam%20ille'));
    service.directory({ skill: ' Kafka ', city: '', availability: 'LISTENING', remote: true, page: 2 }).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/members')).request.params.toString())
      .toBe('page=2&skill=Kafka&availability=LISTENING&remote=true');
    service.directory({}).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/members')).request.params.toString()).toBe('page=0');
    service.post('Bonjour').subscribe();
    expect(http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/posts')).request.body).toEqual({ text: 'Bonjour', kind: 'POST', details: null, poll: null });
    service.vote(5, 1).subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/posts/5/vote')).request.params.get('choice')).toBe('1');
    service.react(5, 'BRAVO').subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/posts/5/like')).request.params.get('reaction'))
      .toBe('BRAVO');
    service.react(5, null).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/posts/5/like'));
    service.likers(5).subscribe();
    http.expectOne(call => call.url.endsWith('/network/posts/5/likes'));
    service.comments(5).subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/posts/5/comments'));
    service.comment(5, 'Merci', 3).subscribe();
    expect(http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/posts/5/comments')).request.body)
      .toEqual({ text: 'Merci', parentId: 3 });
    service.deleteComment(3).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/comments/3'));
    service.hideComment(3, true).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/comments/3/hidden')).request.params.get('hidden')).toBe('true');
    service.closeComments(5, false).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/posts/5/comments-closed')).request.params.get('closed')).toBe('false');
    service.pinComment(5, 3).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/posts/5/pinned-comment')).request.params.get('commentId')).toBe('3');
    service.pinComment(5, null).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/posts/5/pinned-comment')).request.params.keys()).toEqual([]);
    service.editPost(5, 'Revu').subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/posts/5')).request.body).toEqual({ text: 'Revu' });
    service.drafts().subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/drafts'));
    service.createDraft('Plus tard', '2026-11-16T08:00:00.000Z').subscribe();
    expect(http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/drafts')).request.body)
      .toEqual({ text: 'Plus tard', scheduledAt: '2026-11-16T08:00:00.000Z' });
    service.updateDraft(2, 'Relu', null).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/drafts/2'));
    service.deleteDraft(2).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/drafts/2'));
    service.publishDraft(2).subscribe();
    http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/drafts/2/publish'));
    service.repost(5, 'À lire').subscribe();
    expect(http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/posts/5/reposts')).request.body).toEqual({ text: 'À lire' });
    service.repostsOff(5, true).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/posts/5/reposts-off')).request.params.get('off')).toBe('true');
    service.bookmark(5, true).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/posts/5/bookmark'));
    service.bookmark(5, false).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/posts/5/bookmark'));
    service.saved('kafka', 1).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/bookmarks')).request.params.toString()).toBe('tag=kafka&page=1');
    service.saved(null).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/bookmarks')).request.params.toString()).toBe('page=0');
    service.tagPage('kafka', 1).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/tags/kafka')).request.params.get('page')).toBe('1');
    service.followedTags().subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/tags'));
    service.followTag('kafka', true).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/tags/kafka/follow'));
    service.followTag('kafka', false).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/tags/kafka/follow'));
    service.postVersions(5).subscribe();
    http.expectOne(call => call.url.endsWith('/network/posts/5/versions'));
    service.deletePost(5).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/posts/5'));
    service.feed().subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/feed')).request.params.get('page')).toBe('0');
    service.memberPosts('leo', 2).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/members/leo/posts')).request.params.get('page')).toBe('2');
    service.notifications().subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/notifications'));
    service.unreadNotifications().subscribe();
    http.expectOne(call => call.url.endsWith('/network/notifications/unread'));
    service.readNotifications().subscribe();
    http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/notifications/read'));
    service.notificationSettings().subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/notifications/settings'));
    service.saveNotificationSettings(['LIKE']).subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/notifications/settings')).request.body)
      .toEqual({ off: ['LIKE'] });
    service.saveNotificationSettings([], ['LIKE']).subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/notifications/settings')).request.body)
      .toEqual({ off: [], emailed: ['LIKE'] });
    service.suggestions().subscribe();
    http.expectOne(call => call.url.endsWith('/network/suggestions'));
    service.member('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille'));
    service.recommendations('camille').subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/members/camille/recommendations')).request.context.get(SILENT_HTTP_ERRORS))
      .toBeTrue();
    service.mutual('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille/mutual'));
    service.postStats(4).subscribe();
    http.expectOne(call => call.url.endsWith('/network/posts/4/stats'));
    service.activity(true).subscribe();
    expect(http.expectOne(call => call.url.endsWith('/network/activity')).request.context.get(SILENT_HTTP_ERRORS)).toBeTrue();
    service.recordView('camille').subscribe();
    expect(http.expectOne(call => call.method === 'POST' && call.url.endsWith('/network/members/camille/views')).request.context
      .get(SILENT_HTTP_ERRORS)).toBeTrue();
    service.pageViews(true).subscribe();
    http.expectOne(call => call.method === 'GET' && call.url.endsWith('/network/page-views'));
    service.setPrivateViewing(true).subscribe();
    expect(http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/page-views/private')).request.params.get('on'))
      .toBe('true');
    service.page('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille/page'));
    service.follow('camille').subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/members/camille/follow'));
    service.unfollow('camille').subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/members/camille/follow'));
    service.followers('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille/followers'));
    service.following('camille').subscribe();
    http.expectOne(call => call.url.endsWith('/network/members/camille/following'));
    service.mute('leo', true).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/members/leo/mute'));
    service.mute('leo', false).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/members/leo/mute'));
    service.block('leo', true).subscribe();
    http.expectOne(call => call.method === 'PUT' && call.url.endsWith('/network/members/leo/block'));
    service.block('leo', false).subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/members/leo/block'));
    service.restrictions().subscribe();
    http.expectOne(call => call.url.endsWith('/network/restrictions'));
    service.removeFollower('leo').subscribe();
    http.expectOne(call => call.method === 'DELETE' && call.url.endsWith('/network/followers/leo'));
    http.verify();
  });
});
